const file = process.argv[2];
if (!file) throw new Error("Give the path to f1-circuits.geojson.");
const data = JSON.parse(fs.readFileSync(file, "utf8"));
const byId = new Map(data.features.map((f) => [f.properties.id, f]));

function resample(pts, step) {
  const out = [pts[0]];
  let carry = 0;
  for (let i = 1; i < pts.length; i++) {
    let [ax, az] = pts[i - 1];
    const [bx, bz] = pts[i];
    let seg = Math.hypot(bx - ax, bz - az);
    let t = step - carry;
    while (t <= seg) {
      const f = t / seg;
      out.push([ax + (bx - ax) * f, az + (bz - az) * f]);
      t += step;
    }
    carry = seg - (t - step);
  }
  return out;
}

const tracks = [];
for (const [id, name, blurb] of PICK) {
  const f = byId.get(id);
  if (!f) throw new Error(`No ${id} in the dataset.`);
  const c = f.geometry.coordinates;
  const lat0 = c.reduce((a, p) => a + p[1], 0) / c.length;
  const lon0 = c.reduce((a, p) => a + p[0], 0) / c.length;
  // East → +x, north → -z (so north is up when seen from above).
  let pts = c.map(([lon, lat]) => [(lon - lon0) * 111320 * Math.cos((lat0 * Math.PI) / 180) * SCALE, -(lat - lat0) * 110540 * SCALE]);
  if (Math.hypot(pts[0][0] - pts.at(-1)[0], pts[0][1] - pts.at(-1)[1]) < 1) pts = pts.slice(0, -1);
  pts.push(pts[0]); // closed
  const even = resample(pts, SPACING).slice(0, -1);
  tracks.push({
    id: id.split("-")[0] + id.split("-")[1].slice(2),
    name,
    blurb,
    realLength: f.properties.length,
    points: even.flatMap(([x, z]) => [Math.round(x * 10), Math.round(z * 10)]), // decimeters
  });
}

